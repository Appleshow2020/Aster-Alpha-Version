import re
print(repr(re.sub(r'(x)|(a)', r'[\1|\2]', 'axb')))
print(re.findall(r'\w+','héllo wörld'))
print(bool(re.match(r'\w','é')), bool(re.match(r'\d','٣')), bool(re.match(r'\s','\u00a0')))
print(repr(re.sub(r'a', r'\g<0>\g<0>', 'a')))
print(repr(re.sub(r'(?P<w>\w+)', r'[\g<w>]', 'hi yo')))
print(repr(re.sub(r'(\w)', r'$1$1', 'ab')))
print(re.findall(r'(a)?b', 'b'))
print(re.match(r'a{2,3}', 'aaaa'))
print(re.match(r'a{2,3}?', 'aaaa'))
print(re.match(r'a{2,3}+', 'aaaa'))
print(re.match(r'(?:ab)*?c', 'ababc'))
print(re.match(r'(?i)[a-z]+', 'ABc'))
print(re.match(r'(?i)\w+', 'ÄBC'))
print(re.split(r'', 'abc', maxsplit=2))
print(re.findall(r'', 'ab'))
